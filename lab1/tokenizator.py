# tokenizator.py
#
# Модуль отвечает за:
#   4) обезличивание персональных данных (замена на [PHONE], [EMAIL], ...)
#   5) токенизацию + удаление стоп-слов и пунктуации
#   6) лемматизацию слов
#
# Использование:
#   tok = Tokenizator(stopwords=my_stopwords)
#   result = tok.process(text, entities)
#
# result = {
#   "anonymized_text": "...",
#   "tokens": [...],
#   "lemmas": [...]
# }

import re
import pymorphy3
class Tokenizator:
    
    # Регулярные выражения для поиска сущностей.
    # Согласованы с parser.py — если parser.py что-то не поймал,
    # tokenizator сможет заменить сам.
    
    PATTERNS = {
        "EMAIL":   r"[\w\.-]+@[\w\.-]+\.\w+",
        "PHONE":   r"\+?\d[\d\s\-\(\)]{7,}\d",
        "DATE":    r"\d{2}[./-]\d{2}[./-]\d{2,4}|\d{4}-\d{2}-\d{2}",
        "URL":     r"(?:https?://)?(?:www\.)?[\w\-]+\.[\w\-]+(?:/\S*)?",
        "PRICE":   r"\d[\d\s]*(?:руб|rub|р|₽)\w*\.?",
        "HASHTAG": r"#\w+",
    }
    def __init__(self, stopwords=None):
        """
        stopwords — список стоп-слов. Если None — берём встроенный набор.
        """
        if stopwords is None:
            stopwords = self._default_stopwords()

        # set для быстрого поиска (O(1) вместо O(n))
        self.stopwords = set(w.lower() for w in stopwords)
        # MorphAnalyzer для лемматизации
        self.morph = pymorphy3.MorphAnalyzer()
    # ------------------------------------------------------------------
    # Пункт 4. Обезличивание
    # ------------------------------------------------------------------
    def anonymize(self, text, entities=None):
        """
        Заменяет сущности на маркеры [URL], [EMAIL], [PHONE], [DATE],
        [PRICE], [HASHTAG].
        text     — строка
        entities — словарь со списками найденных сущностей (может быть None)
        Возвращает строку с маркерами.
        """
        if not text:
            return ""
            
        # Порядок важен: URL и EMAIL — длинные, их заменяем первыми,
        # чтобы PHONE или PRICE не «съели» часть.
        
        replacements = [
            ("URL",     self.PATTERNS["URL"]),
            ("EMAIL",   self.PATTERNS["EMAIL"]),
            ("PHONE",   self.PATTERNS["PHONE"]),
            ("DATE",    self.PATTERNS["DATE"]),
            ("PRICE",   self.PATTERNS["PRICE"]),
            ("HASHTAG", self.PATTERNS["HASHTAG"]),
        ]

        anonymized = text
        for marker, pattern in replacements:
            anonymized = re.sub(pattern, f"[{marker}]", anonymized,
                                flags=re.IGNORECASE)
        return anonymized
    # ------------------------------------------------------------------
    # Пункт 5.1. Токенизация (без удаления стоп-слов — это отдельный метод)
    # ------------------------------------------------------------------
    def tokenize(self, text, remove_markers=True):
        """
        Разбивает текст на токены.
        remove_markers=True — убираем маркеры [URL], [PHONE] из текста
        (по заданию они должны остаться только в отдельных столбцах).
        Возвращает список токенов (строк).
        """
        if not text:
            return []
        # 1) Убираем маркеры [XXX]
        if remove_markers:
            text = re.sub(r"\[[A-ZА-Я]+\]", " ", text)
        # 2) Нижний регистр
        text = text.lower()
        # 3) Только буквенные последовательности.
        #    Так отсекаются пунктуация, цифры, emoji, ***, ###, !!!.
        tokens = re.findall(r"[а-яёa-z]+", text)
        # 4) Убираем односимвольный шум
        tokens = [t for t in tokens if len(t) > 1]
        return tokens
    # ------------------------------------------------------------------
    # Пункт 5.2. Удаление стоп-слов (отдельный метод)
    # ------------------------------------------------------------------
    def remove_stop(self, tokens):
        """
        Удаляет стоп-слова из списка токенов.
        Возвращает очищенный список.
        """
        if not tokens:
            return []
        return [t for t in tokens if t not in self.stopwords]
    # ------------------------------------------------------------------
    # Пункт 6. Лемматизация
    # ------------------------------------------------------------------
    def lemmatize(self, tokens):
        """
        Приводит токены к словарной форме через pymorphy3.
        """
        if not tokens:
            return []
        lemmas = []
        for token in tokens:
            parsed = self.morph.parse(token)[0]
            lemmas.append(parsed.normal_form)
        return lemmas
    # ------------------------------------------------------------------
    # Общий метод: обезличить → токенизировать → удалить стоп-слова → лемматизировать
    # ------------------------------------------------------------------
    def process(self, text, entities=None):
        """
        Полный цикл обработки одного сообщения.
        """
        if entities is None:
            entities = {}
        # 1. Обезличивание
        anonymized = self.anonymize(text, entities)
        # 2. Токенизация
        tokens = self.tokenize(anonymized, remove_markers=True)
        # 3. Удаление стоп-слов
        tokens = self.remove_stop(tokens)
        # 4. Лемматизация
        lemmas = self.lemmatize(tokens)
        return {
            "anonymized_text": anonymized,
            "tokens": tokens,
            "lemmas": lemmas,
        }
